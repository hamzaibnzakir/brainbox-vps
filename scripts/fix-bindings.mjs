// Post-process ts-rs output:
//  - 64-bit integers are serialized by serde_json as JSON numbers; every value we
//    send (timestamps, byte counts) is far below 2^53, so type them as `number`.
//  - generate an index.ts barrel.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../src/types/generated/", import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
for (const f of files) {
  const p = join(dir, f);
  const src = readFileSync(p, "utf8");
  const out = src.replace(/\bbigint\b/g, "number");
  if (out !== src) writeFileSync(p, out);
}
writeFileSync(
  join(dir, "index.ts"),
  "// Generated by scripts/fix-bindings.mjs — do not edit.\n" +
    files.map((f) => `export type * from "./${f.replace(/\.ts$/, "")}";`).join("\n") +
    "\n",
);
console.log(`bindings: ${files.length} types`);
